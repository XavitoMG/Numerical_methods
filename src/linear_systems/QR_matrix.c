/*

Until now, QR decomposition with Householder method has been the most
complicated method to understand correctly. The objective of this method
is apply the Householder function P(u), which is a reflection of the hyperplane
defined by the normal vector u, to every column and restrict the components until
you get a triangular matrix.

Let (u_1,...,u_n) be the columns of a square matrix on R^n (can be rectangular with
m<n columns). Since P(u) is a orthogonal matrix (reflections are isometries, thus, can be 
represented with an orthogonal matrix H=P(u)), the objective is multiply the matrix A with
orthogonal matrices until it transforms into a triangular matrix.

Take u_1 = (u_11,...,u_1n), and consider the Householder matrix P(v) with v = u-ae_1 where e_1
is the first vector of the standard basis of R^n and a=sign(u_11)*|u|, it can be proven that
P(v)u_1=ae_1, so this transformation sends u to the line generated by e_1
Now, since all of the other vectors are linearly independent with e_1 (since ker(P(u))=0),
The projection of every vector in the hyperplane generated by the normal vector e_1 is also
linearly independent and the resultant matrix would be:

( a x x x ... x )
( 0 x x x ... x )
( 0 x x x ... x )
( . . . .     . )
( 0 x x x ... x )

And the projection of the hyperplane of every other vector corresponds to the submatrix defined
by deleting the first row and the first column of the previous matrix. We can observe that the
projection is linearly independent since submatrix rank is still full due to the fact that the
resultant matrix is product of non-singular matrices. We apply the same logic to this submatrix 
with an orthogonal matrix of the form:

(I 0)
(0 H)

Where I is the identity (in this case, of dimension 1) and H the householder matrix
applied to the restriction of the hyperplane (the submatrix (n-1)x(n-1)). 
This matrix is also orthogonal since I and H are orthogonal and are "disjoint".

If we apply this logic n times, we get a finite sequence of orthogonal matrices Q_1,...,Q_n
and a triangular matrix R that satisfies Q_1 * ... * Q_n * A = R. Since every Q_i is orthogonal,
every one satisfies Q_i * (Q_i)^T = I, so A = (Q_n)^T * ... * (Q_1)^T * R = QR 
with Q = (Q_n)^T * ... * (Q_1)^T orthogonal (we implicited used that to prove that A=QR).

With this relation, we can solve Ax = b solving QRx=b => Rx = (Q^T)b

*/

#include <math.h>

#define sgn(i) (i>=0?1:-1)

double avg (int n, double v[n], double u[n]) {
    double sum = 0;
    for (int i = 0; i < n; i++) sum += v[i] * u[i];
    return sum;
}

int QR_matrix (int n, int m, double *A, int *p, double tol) {

    #define A(i,j) A[i*n + j]

    double v[m];
    double sum = 0;
    double modv = 0;
    double a = 0;
    double maxmod = 0;
    int max = 0;

    for (int i = 0; i < m; i++) p[i] = i;


    for (int k = 0; k < n; k++) {

        max = p[k];
        maxmod = 0;
        for (int j = k; j < n; j++) {
            sum = 0;
            for (int i = k; i < m; i++) sum += A(i,p[j]) * A(i,p[j]);
            if (sum > maxmod) {
                max = j;
                maxmod = sum;
            }
        }
        sum = p[max];
        p[max] = p[k];
        p[k] = sum;

        if (fabs(A(k,p[k])) < tol) {
            for (int i = 0; i < n; i++) if(fabs(A(i,p[i])) < tol) A(i,p[i]) = 0.0;
            break;
        }

        sum = 0;

        for (int i = 0; i < m; i++) {
            if (i < k) v[i] = 0;
            else {
                v[i] = A(i,p[k]);
                sum += v[i]*v[i];
            }

        }

        a = -sgn(A(k,p[k])) * sqrt(sum);

        v[k] -= a;

        modv = avg(m,v,v);

        for (int j = k; j < n; j++) {
            sum = 0;
            for (int i = 0; i < m; i++) sum += v[i] * A(i,p[j]);
            for (int i = k; i < m; i++) {
                A(i,p[j]) -= 2/(modv) * v[i] * sum;
            }
        }

        for (int i = k+1; i < m; i++) {
            A(i,p[k]) = v[i]/v[k];
        }

    }

    return 0;


}